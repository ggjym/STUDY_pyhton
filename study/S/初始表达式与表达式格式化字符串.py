# 续接 字符串格式化。py/字符串格式化 3
# 表达式定义：一条具有明确运算结果的代码语句，如：1+1，1*2(2+3)...
# 又或者：“name="xxx"“中的“"xxx"；“age=18+18“中的“18+18“

print(f"我是：{"XXX"},我的电话是：{123456*100+78}，我线上状态是：{bool(1-1)}")
#>>我是：XXX,我的电话是：12345678，我线上状态是：False

print("我是：%s，我的电话是：%d，我线上状态是：%s"%("XXX",123456*100+78,bool(1-1)))
#>>我是：XXX,我的电话是：12345678，我线上状态是：False